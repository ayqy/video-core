#!/usr/bin/env python3
"""Rebuild the fixed offline cover font from the checked-in, unmodified original.

Usage: python3 scripts/embed_cover_typeface.py [--display] [--check]
No network, font registration, archive, or runtime resource bundle is involved.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
from pathlib import Path
import textwrap
import zlib

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL = ROOT / "ThirdParty/Fonts/SmileySans/SmileySans-Oblique.ttf"
LICENSE = ROOT / "ThirdParty/Fonts/SmileySans/LICENSE"
OUTPUT = ROOT / "Sources/VideoMedia/CoverTypeface.swift"
DISPLAY_ORIGINAL = ROOT / "ThirdParty/Fonts/DouyinSans/DouyinSansBold.ttf"
DISPLAY_LICENSE = ROOT / "ThirdParty/Fonts/DouyinSans/LICENSE"
DISPLAY_OUTPUT = ROOT / "Sources/VideoMedia/CoverDisplayTypeface.swift"
FONT_BYTES = 2_629_764
FONT_SHA256 = "b447d7e781f08bc95c4c9f23ba71ed2b8ebb639aa7184485c71c4ca5afcd25c4"
LICENSE_SHA256 = "9401f4050f1b66c26b6ccdc8b0e14a3c1cc37aac122eda84386f25854a9bec72"


def render(*, display=False) -> bytes:
    font = (DISPLAY_ORIGINAL if display else ORIGINAL).read_bytes()
    license_data = (DISPLAY_LICENSE if display else LICENSE).read_bytes()
    font_bytes = 1_919_404 if display else FONT_BYTES
    font_sha = "fbecfacdfac33982774e301073a8d357a09c698cd3134bb6ddec0f5bfc268fa1" if display else FONT_SHA256
    license_sha = "a6d5700a002ea32bcfbe3310253d603997683dac8ac63777e375d06c07c30ea6" if display else LICENSE_SHA256
    if len(font) != font_bytes or hashlib.sha256(font).hexdigest() != font_sha:
        raise ValueError("fixed official cover TTF has changed")
    if hashlib.sha256(license_data).hexdigest() != license_sha:
        raise ValueError("fixed official cover copyright/license has changed")
    compressed = zlib.compress(font, level=9)
    if zlib.decompress(compressed) != font:
        raise ValueError("font compression round trip failed")
    compressed_sha = hashlib.sha256(compressed).hexdigest()
    payload = "\n".join(textwrap.wrap(base64.b64encode(compressed).decode("ascii"), 100))
    license_comment = "\n".join(("// " + line).rstrip() for line in license_data.decode("utf-8").splitlines())
    text = '''// Generated by scripts/embed_cover_typeface.py from the unmodified official
// Smiley Sans v2.0.1 TTF. Do not edit its payload or substitute a system font.
// Upstream: https://github.com/atelier-anchor/smiley-sans/tree/67e3821f4b06cbd7155fa6fa69daff4b6f311b76
// Full source/license: ThirdParty/Fonts/SmileySans/
__LICENSE_COMMENT__

import Foundation
import CoreGraphics
import CoreText
import CZlib
import VideoCore

/// One fixed offline title face, loaded directly from its original bytes.
/// No process/system font registration, filesystem, or Bundle lookup occurs.
public enum CoverTypeface {
    public static let postScriptName = "SmileySans-Oblique"
    public static let sourceBytes = __FONT_BYTES__
    public static let sourceSHA256 = "__FONT_SHA__"

    private static let compressedBytes = __COMPRESSED_BYTES__
    private static let compressedSHA256 = "__COMPRESSED_SHA__"
    private static let cached: Result<CGFont, Error> = Result { try decode() }

    /// A failed embedded face is reported; silently substituting a host font
    /// would change line breaks and invalidate the title's safe crop region.
    public static func font(size: CGFloat) throws -> CTFont {
        guard size.isFinite, size > 0, size <= 4096 else {
            throw VideoError.invalid("封面标题字号须为有效的正数且不超过4096点")
        }
        let face = try cached.get()
        let font = CTFontCreateWithGraphicsFont(face, size, nil, nil)
        guard (CTFontCopyPostScriptName(font) as String) == postScriptName else {
            throw VideoError.unavailable("离线封面字体身份校验失败")
        }
        return font
    }

    private static func decode() throws -> CGFont {
        guard let compressed = Data(base64Encoded: payload, options: .ignoreUnknownCharacters),
              compressed.count == compressedBytes,
              Codec.hash(compressed) == compressedSHA256 else {
            throw VideoError.unavailable("内嵌封面字体压缩数据校验失败")
        }
        var stream = z_stream()
        let initialized = inflateInit_(&stream, ZLIB_VERSION, Int32(MemoryLayout<z_stream>.size))
        guard initialized == Z_OK else {
            throw VideoError.unavailable("离线封面字体解压器不可用")
        }
        defer { inflateEnd(&stream) }
        // The output allocation is the hard pinned original size. No attacker
        // supplied size or growing decompression buffer is accepted.
        var data = Data(count: sourceBytes)
        let status = compressed.withUnsafeBytes { source in
            data.withUnsafeMutableBytes { destination -> Int32 in
                stream.next_in = UnsafeMutablePointer(mutating: source.bindMemory(to: Bytef.self).baseAddress)
                stream.avail_in = uInt(compressed.count)
                stream.next_out = destination.bindMemory(to: Bytef.self).baseAddress
                stream.avail_out = uInt(destination.count)
                return inflate(&stream, Z_FINISH)
            }
        }
        guard status == Z_STREAM_END,
              Int(stream.total_in) == compressedBytes, stream.avail_in == 0,
              Int(stream.total_out) == sourceBytes, stream.avail_out == 0,
              data.count == sourceBytes, Codec.hash(data) == sourceSHA256,
              let provider = CGDataProvider(data: data as CFData),
              let face = CGFont(provider), let actualName = face.postScriptName,
              (actualName as String) == postScriptName else {
            throw VideoError.unavailable("离线封面字体原件或PostScript身份校验失败")
        }
        return face
    }

    private static let payload = """
__PAYLOAD__
"""
}
'''
    replacements = {
        "__LICENSE_COMMENT__": license_comment,
        "__FONT_BYTES__": str(font_bytes),
        "__FONT_SHA__": font_sha,
        "__COMPRESSED_BYTES__": str(len(compressed)),
        "__COMPRESSED_SHA__": compressed_sha,
        "__PAYLOAD__": payload,
    }
    for key, value in replacements.items():
        text = text.replace(key, value)
    if display:
        text = text.replace("// Smiley Sans v2.0.1 TTF.", "// DouyinSansBold TTF.")
        text = text.replace("https://github.com/atelier-anchor/smiley-sans/tree/67e3821f4b06cbd7155fa6fa69daff4b6f311b76",
            "https://github.com/bytedance/fonts/tree/327565b61501d7a6d4902ed6ce417a7bd2ae54e6/DouyinSans")
        text = text.replace("ThirdParty/Fonts/SmileySans/", "ThirdParty/Fonts/DouyinSans/")
        text = text.replace("public enum CoverTypeface {", "public enum CoverDisplayTypeface {")
        text = text.replace('postScriptName = "SmileySans-Oblique"', 'postScriptName = "DOUYINSANSBOLD-GB"')
        text += '''
public extension CoverTypeface {
    static let displayPostScriptName = CoverDisplayTypeface.postScriptName
    static func displayFont(size: CGFloat) throws -> CTFont {
        try CoverDisplayTypeface.font(size: size)
    }
}
'''
    return text.encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in Swift source is reproducible")
    parser.add_argument("--display", action="store_true", help="build the fixed DouyinSansBold display face; legacy remains unchanged")
    options = parser.parse_args()
    result = render(display=options.display)
    output = DISPLAY_OUTPUT if options.display else OUTPUT
    if options.check:
        if output.read_bytes() != result:
            raise ValueError("cover typeface differs from the pinned original and generator")
    else:
        output.write_bytes(result)
    print(("checked" if options.check else "wrote"), output.relative_to(ROOT), len(result), hashlib.sha256(result).hexdigest())


if __name__ == "__main__":
    main()
