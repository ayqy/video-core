#!/usr/bin/env python3
"""Embed the unmodified official ChillRoundF face using the existing decoder.

Usage: python -B scripts/embed_island_typeface.py [--check]
No network, font registration, subsetting, Bundle or Native process is involved.
"""
import argparse
import ast
import base64
import hashlib
from pathlib import Path
import textwrap
import zlib

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL = ROOT/'ThirdParty/Fonts/ChillRoundF/ChillRoundF-v3.0.ttf'
LICENSE = ROOT/'ThirdParty/Fonts/ChillRoundF/LICENSE'
TEMPLATE = ROOT/'scripts/embed_cover_typeface.py'
OUTPUT = ROOT/'Sources/VideoMedia/IslandTypeface.swift'
FONT_BYTES = 6168772
FONT_SHA = '7dae804b344f7bc1a1c8426b9515e9b54d7baac3e123263d0bae94d0a305a732'
LICENSE_SHA = 'd45891f8adfd21368c98e803603df1f575ff3fc4a6ec713ba7ccf0e3cba15b28'


def render():
    font, license_data = ORIGINAL.read_bytes(), LICENSE.read_bytes()
    if len(font) != FONT_BYTES or hashlib.sha256(font).hexdigest() != FONT_SHA:
        raise ValueError('unmodified official ChillRoundF v3.0 original changed')
    if hashlib.sha256(license_data).hexdigest() != LICENSE_SHA:
        raise ValueError('official ChillRoundF OFL/copyright changed')
    # Reuse the current offline decoder template rather than introducing a
    # system font registration or another decoding/verification implementation.
    tree = ast.parse(TEMPLATE.read_text())
    templates = [n.value.value for n in ast.walk(tree) if isinstance(n,ast.Assign)
        and isinstance(n.value,ast.Constant) and isinstance(n.value.value,str)
        and 'public enum CoverTypeface {' in n.value.value and '__PAYLOAD__' in n.value.value]
    if len(templates) != 1:
        raise ValueError('existing offline decoder must expose exactly one font template')
    _, body = templates[0].split('__LICENSE_COMMENT__',1)
    body = body.replace('public enum CoverTypeface {','public enum IslandTypeface {')
    body = body.replace('SmileySans-Oblique','ChillRoundF').replace('封面字体','岛屿主题字体')
    compressed = zlib.compress(font,9)
    if zlib.decompress(compressed) != font:
        raise ValueError('unmodified original compression round trip failed')
    values = {
        '__FONT_BYTES__':str(FONT_BYTES), '__FONT_SHA__':FONT_SHA,
        '__COMPRESSED_BYTES__':str(len(compressed)),
        '__COMPRESSED_SHA__':hashlib.sha256(compressed).hexdigest(),
        '__PAYLOAD__':'\n'.join(textwrap.wrap(base64.b64encode(compressed).decode(),100)),
    }
    for key,value in values.items():
        body = body.replace(key,value)
    header = ('// Generated by scripts/embed_island_typeface.py from the unmodified official\n'
              '// ChillRoundF v3.0 TTF. No glyph, font name or source byte is modified.\n'
              '// Upstream: https://github.com/Warren2060/ChillRound\n'
              '// Full source/license: ThirdParty/Fonts/ChillRoundF/\n')
    notice = '\n'.join(('// '+line).rstrip() for line in license_data.decode().splitlines())
    return (header+notice+body).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    output = render()
    if args.check:
        if OUTPUT.read_bytes() != output:
            raise ValueError('IslandTypeface.swift differs from the fixed offline generator')
    else:
        OUTPUT.write_bytes(output)
    print('island_typeface='+('checked' if args.check else 'generated')+' source_bytes='+str(FONT_BYTES))


if __name__ == '__main__':
    main()
